#!/usr/bin/env python3
"""Replay the final direct uniform references and optional numerical checks.

The study directory must already contain CASE/base.mesh and CASE/targets.csv,
normally generated by run_study.py. Existing completed outputs are reused only
when their command, binary, input hashes and thread count match. Partial or
conflicting outputs are never overwritten: choose a fresh study directory.

    python3 general_domain/run_reference_checks.py --threads 16
    python3 general_domain/run_reference_checks.py --threads 16 --validation

Final references use uniform level 2, p=16 and near-subdivision depth 4. Optional
checks use the L-shaped prism and run separately under DIRECTORY/validation.
"""
import argparse
import csv
import hashlib
import json
import math
import os
from pathlib import Path
import subprocess
import time

HERE = Path(__file__).resolve().parent
CASES = ("sphere", "l_prism", "perforated_cube")
TEMPLATES = ":".join(
    str(Path("/usr/local/include/AFEPack/template") / name) + "/"
    for name in ("triangle", "twin_triangle", "tetrahedron",
                 "twin_tetrahedron", "four_tetrahedron")
)


def digest(path):
    checksum = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            checksum.update(block)
    return checksum.hexdigest()


def read_rows(path):
    with path.open(newline="") as stream:
        rows = list(csv.DictReader(stream))
    if not rows:
        raise RuntimeError(f"Empty target/value file: {path}")
    return rows


def check_targets(value_path, target_path):
    values, targets = read_rows(value_path), read_rows(target_path)
    if len(values) != len(targets):
        raise RuntimeError(f"Target count mismatch in {value_path}")
    for value, target in zip(values, targets):
        if any(value[key] != target[key] for key in ("id", "group", "x", "y", "z")):
            raise RuntimeError(f"Target coordinates/order mismatch in {value_path}")
        if not math.isfinite(float(value["potential"])):
            raise RuntimeError(f"Nonfinite potential in {value_path}")


def difference(first_path, second_path):
    first, second = read_rows(first_path), read_rows(second_path)
    if len(first) != len(second):
        raise RuntimeError("Cannot compare different target counts")
    pairs = []
    for a, b in zip(first, second):
        if any(a[key] != b[key] for key in ("id", "group", "x", "y", "z")):
            raise RuntimeError("Cannot compare different target coordinates/order")
        pairs.append((a["group"], float(a["potential"]), float(b["potential"])))
    result = {}
    for group in ("volume", "core", "all"):
        selected = [row for row in pairs if group == "all" or row[0] == group]
        if not selected:
            continue
        error_squared = sum((a - b)**2 for _, a, b in selected)
        norm_squared = sum(b * b for _, _, b in selected)
        if norm_squared <= 0:
            raise RuntimeError("Cannot form relative error with a zero reference norm")
        result[group] = {
            "targets": len(selected),
            "maximum_absolute_difference": max(abs(a-b) for _, a, b in selected),
            "relative_l2_sample_difference": math.sqrt(error_squared / norm_squared),
        }
    return result


def execute(binary, mesh, targets, prefix, arguments, threads, direct=False):
    for path in (binary, mesh, targets):
        if not path.is_file():
            raise FileNotFoundError(
                f"Missing {path}. Build the driver and generate the study inputs with run_study.py first.")
    prefix.parent.mkdir(parents=True, exist_ok=True)
    # Keep this order compatible with the recorded final-reference commands.
    command = [str(binary), "--mode", arguments[0], "--mesh", str(mesh),
               "--targets", str(targets)] + arguments[1:] + ["--output", str(prefix)]
    expected = {
        "command": command,
        "threads": threads,
        "binary_sha256": digest(binary),
        "mesh_sha256": digest(mesh),
        "target_sha256": digest(targets),
    }
    job_path = prefix.with_suffix(".job.json")
    json_path = prefix.with_suffix(".json")
    value_path = prefix.with_suffix(".values.csv")
    direct_path = prefix.with_suffix(".direct.csv")
    required = [json_path, value_path] + ([direct_path] if direct else [])
    if job_path.exists() and all(path.exists() for path in required):
        previous = json.loads(job_path.read_text())
        if previous.get("returncode") == 0 and all(
                previous.get(key) == value for key, value in expected.items()):
            check_targets(value_path, targets)
            if direct:
                check_targets(direct_path, targets)
            print(f"REUSE {prefix.name}", flush=True)
            return
        raise RuntimeError(
            f"Conflicting provenance for {prefix}; results were not changed. Use a fresh directory.")
    suffixes = (".job.json", ".json", ".values.csv", ".direct.csv", ".log", ".dx")
    existing = [str(prefix.with_suffix(suffix)) for suffix in suffixes
                if prefix.with_suffix(suffix).exists()]
    if existing:
        raise RuntimeError(
            "Partial or untracked output will not be overwritten: " + ", ".join(existing))

    env = dict(os.environ, AFEPACK_TEMPLATE_PATH=TEMPLATES,
               OMP_NUM_THREADS=str(threads), OMP_DYNAMIC="FALSE",
               OMP_PLACES="cores", OMP_PROC_BIND="spread")
    record = dict(expected, status="running", purpose="Numerical reference validation; pilot timing")
    record["environment"] = {key: env[key] for key in (
        "AFEPACK_TEMPLATE_PATH", "OMP_NUM_THREADS", "OMP_DYNAMIC", "OMP_PLACES", "OMP_PROC_BIND")}
    with job_path.open("x") as stream:
        json.dump(record, stream, indent=2)
        stream.write("\n")
    print(f"RUN {prefix.name}, threads={threads}", flush=True)
    start = time.monotonic()
    with prefix.with_suffix(".log").open("x") as log:
        process = subprocess.run(command, cwd=HERE, env=env,
                                 stdout=log, stderr=subprocess.STDOUT)
    record.update(returncode=process.returncode, wall_s=time.monotonic()-start,
                  status="complete" if process.returncode == 0 else "failed")
    # Only the manifest created by this invocation is updated here.
    job_path.write_text(json.dumps(record, indent=2)+"\n")
    if process.returncode:
        raise RuntimeError(f"{prefix.name} failed; inspect {prefix.with_suffix('.log')}")
    if not all(path.exists() for path in required):
        raise RuntimeError(f"Missing expected output for {prefix.name}")
    check_targets(value_path, targets)
    if direct:
        check_targets(direct_path, targets)
    print(f"DONE {prefix.name}: {record['wall_s']:.2f} s", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--directory", type=Path, default=HERE / "runs" / "pilot_20261108")
    parser.add_argument("--threads", type=int, default=16)
    parser.add_argument("--cases", nargs="+", choices=CASES, default=list(CASES))
    parser.add_argument("--validation", action="store_true",
                        help="Also run all-near equivalence and p12 depth3/depth4 checks on L-prism")
    parser.add_argument("--validation-threads", type=int, default=4)
    args = parser.parse_args()
    if min(args.threads, args.validation_threads) < 1:
        parser.error("thread counts must be positive")
    directory = args.directory.resolve()
    binary = HERE / "compare_general_domain"
    for case in dict.fromkeys(args.cases):
        folder = directory / case
        prefix = folder / "uniform_L2_p16_d4"
        execute(binary, folder / "base.mesh", folder / "targets.csv", prefix,
                ["reference", "--level", "2", "--p", "16", "--near-depth", "4"],
                args.threads)
        older = folder / "uniform_L2_p12.values.csv"
        if older.exists():
            print(f"{case}: p12/depth3 versus final p16/depth4\n" + json.dumps(
                difference(older, prefix.with_suffix(".values.csv")), indent=2), flush=True)

    if args.validation:
        folder = directory / "l_prism"
        validation = directory / "validation"
        mesh, targets = folder / "base.mesh", folder / "targets.csv"
        all_near = validation / "check_l_prism_all_near"
        execute(binary, mesh, targets, all_near,
                ["solve", "--uniform", "--level", "0", "--p", "6", "--P", "4",
                 "--theta", "1e-6", "--same-direct"], args.validation_threads, direct=True)
        all_near_stats = json.loads(all_near.with_suffix(".json").read_text())
        if all_near_stats["far_entries"] != 0 or (
                all_near_stats["near_entries"] != all_near_stats["N"]**2):
            raise RuntimeError("The all-near validation did not produce a complete direct list")
        all_near_difference = difference(
            all_near.with_suffix(".values.csv"), all_near.with_suffix(".direct.csv"))
        if all_near_difference["all"]["relative_l2_sample_difference"] > 1e-11:
            raise RuntimeError("All-near treecode and same-mesh direct integration disagree")
        depth_prefixes = []
        for depth in (3, 4):
            prefix = validation / f"check_l_prism_uniform_L2_p12_d{depth}"
            execute(binary, mesh, targets, prefix,
                    ["reference", "--level", "2", "--p", "12", "--near-depth", str(depth)],
                    args.validation_threads)
            depth_prefixes.append(prefix)
        summary = {
            "all_near_tree_vs_direct": all_near_difference,
            "uniform_L2_p12_depth3_vs_depth4": difference(
                depth_prefixes[0].with_suffix(".values.csv"),
                depth_prefixes[1].with_suffix(".values.csv")),
        }
        print("Numerical validation checks:\n" + json.dumps(summary, indent=2), flush=True)
        # Stable, idempotent summary; differing old summaries are not erased.
        summary_path = validation / "check_summary.json"
        if summary_path.exists():
            if json.loads(summary_path.read_text()) != summary:
                raise RuntimeError(f"Conflicting existing summary {summary_path}")
        else:
            with summary_path.open("x") as stream:
                json.dump(summary, stream, indent=2)
                stream.write("\n")


if __name__ == "__main__":
    main()
